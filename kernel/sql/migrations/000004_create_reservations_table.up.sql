CREATE TABLE reservations (
    id SERIAL PRIMARY KEY,
    xid UUID NOT NULL UNIQUE,
    user_id INTEGER NOT NULL,
    reservation_date DATE NOT NULL,
    status TEXT DEFAULT 'pending',
    sample_name TEXT NOT NULL,
    sample_amount DOUBLE PRECISION NOT NULL,
    received_note TEXT,
    test_request_number TEXT,
    sample_residue TEXT NOT NULL,
    special_instructions TEXT,
    po_url TEXT,
    po_number TEXT,
    sample_type TEXT NOT NULL,
    feedback_required BOOLEAN DEFAULT FALSE,
    feedback_submitted BOOLEAN DEFAULT FALSE,
    requires_feedback BOOLEAN DEFAULT FALSE,
    mr_approved BOOLEAN DEFAULT FALSE,
    head_approved BOOLEAN DEFAULT FALSE,
    mr_approval_date TIMESTAMP WITH TIME ZONE,
    head_approval_date TIMESTAMP WITH TIME ZONE,
    sample_photo TEXT,
    note TEXT,
    start_test_date TIMESTAMP WITH TIME ZONE,
    end_test_date TIMESTAMP WITH TIME ZONE,
    sap_notes TEXT,
    batch_number TEXT DEFAULT '-',
    lead_time INTEGER,
    sample_taken_date TIMESTAMP WITH TIME ZONE NOT NULL,
    sample_taken_by TEXT NOT NULL,
    is_kan BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE,
    updated_by INTEGER,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
